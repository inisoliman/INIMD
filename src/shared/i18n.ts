const DICTIONARIES: Record<Language, Record<MessageKey, string>> = { ar, en }

export type TFunction = (key: MessageKey, vars?: Record<string, string | number>) => string

export function translate(lang: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = DICTIONARIES[lang] ?? ar
  let text = dict[key] ?? ar[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

export function createTranslator(lang: Language): TFunction {
  return (key, vars) => translate(lang, key, vars)
}

export function isLanguage(value: unknown): value is Language {
  return value === 'ar' || value === 'en'
}
